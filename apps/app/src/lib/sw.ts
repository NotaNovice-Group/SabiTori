import { isNative } from './native';

/**
 * Offline cache for the web app (vite-plugin-pwa, `registerType: 'prompt'`).
 *
 * - Inside the Android app every file is in the APK: no service worker is registered there.
 * - On the web a new version is downloaded in the background but waits: it takes over only when every
 *   SabiTori page has been closed. Until then the open page keeps its own precache, so the parts of the
 *   app it loads later (OCR, the About screen) are still there offline. Nothing asks the person anything.
 */
export function registerServiceWorker(deps: { native?: () => boolean; register?: () => Promise<unknown> } = {}): boolean {
  if ((deps.native ?? isNative)()) return false;
  if (typeof navigator === 'undefined' || !('serviceWorker' in navigator)) return false;
  // sw.js is generated by vite-plugin-pwa with registerType 'prompt': no skipWaiting, no clientsClaim.
  const register = deps.register ?? (() => navigator.serviceWorker.register(import.meta.env.BASE_URL + 'sw.js', { scope: import.meta.env.BASE_URL }));
  void register().catch(() => undefined);
  return true;
}
