// node test/ocr-bench/report.mjs  -> writes RESULTS.md from results/*.json
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const load = (n) => (existsSync(`results/${n}.json`) ? JSON.parse(readFileSync(`results/${n}.json`, 'utf8')) : []);
const pct = (x) => (x * 100).toFixed(1);
const table = (rows) =>
  '| Variant | CER % | Fact recall % | Fact precision % | Fact F1 % | Pages with every fact right | Prep ms | OCR ms | Total ms (max) |\n|---|---|---|---|---|---|---|---|---|\n' +
  rows.map((r) => `| ${r.name} | ${pct(r.cer)} | ${pct(r.recall)} | ${pct(r.precision)} | ${pct(r.f1)} | ${r.perfect}/${r.images.length} | ${r.prepMs.toFixed(0)} | ${r.ocrMs.toFixed(0)} | ${r.totalMs.toFixed(0)} (${r.maxTotalMs.toFixed(0)}) |`).join('\n');
const final = load('final'), timing = load('timing');
const kinds = [...new Set(final[0].images.map((i) => i.kind))];
const byKind = (v) => kinds.map((k) => { const im = v.images.filter((i) => i.kind === k); const tp = im.reduce((a, i) => a + i.facts.tp, 0), fn = im.reduce((a, i) => a + i.facts.fn, 0); return `${(100 * tp / Math.max(1, tp + fn)).toFixed(0)}`; });
const L = final.find((v) => v.name === 'legacy fra+eng'), D = final.find((v) => v.name === 'default fra+eng +retry');
const kindTable = `| Document | ${kinds.join(' | ')} |\n|---|${kinds.map(() => '---').join('|')}|\n| Before (recall %) | ${byKind(L).join(' | ')} |\n| After (recall %) | ${byKind(D).join(' | ')} |`;
const md = `# OCR benchmark results

Generated by \`test/ocr-bench/report.mjs\` from \`results/*.json\`. 30 synthetic Cameroonian documents (ENEO / CAMWATER bills with tables,
school-fee notices, hospital appointment letters, MoMo SMS screenshots; French and English), degraded with perspective tilt up to 8 deg,
rotation up to 5 deg, desk background, uneven light, creases, low resolution, blur, noise and JPEG artefacts (two shots are turned 90 / 180 deg).
Tesseract.js 7 in Node, fra+eng, same traineddata as the app (\`public/ocr\`).

**Fact accuracy** = dates, FCFA amounts and phone numbers that \`@sabitori/core\` \`extractFacts\` finds in the OCR text, compared with the facts it
finds in the ground-truth text (so the metric measures what OCR noise destroys, not extractor coverage). Recall = share of true facts recovered;
precision = share of reported facts that are true; a wrong digit is both a miss and a false fact. CER = character error rate of the whole page.
The default pipeline was chosen by fact F1, not CER.

## Before / after (the headline)

${table(final.filter((v) => ['legacy fra+eng', 'default fra+eng', 'default fra+eng +retry'].includes(v.name)))}

"legacy" is the previous app code: downscale to 1800 px, greyscale, contrast 1.25. "default" is \`PREP_DEFAULT\` in \`src/lib/ocr-prep.ts\`; "+retry" adds the
half-turn retry when Tesseract confidence is below 55 (what \`recognise()\` ships). Timings in this table were measured with 3 parallel workers; see Timing.

Fact recall by document type (before, after):

${kindTable}

## Which pipeline steps earn their place (cumulative, run before the final fixes: no invert step, no half-turn retry)

${table(load('steps'))}

Reading it: normalisation alone does not help unless the desk is cropped away first (Tesseract wastes time and invents text on the background);
Sauvola binarisation hurts (it throws away the grey edge information the LSTM uses) so it stays available but off; upscaling small text helps both recall
and precision.
Deskew is neutral within the noise of a 30-page set (E to F is -1.9 F1 here, +0.8 in the tuning table T5 vs T2); it is kept because tilted pages are the stated problem and the unit tests verify it recovers known angles to under 0.8 deg. A sampling bug in the skew estimator (stride aliasing with the projection bins) was found by the unit tests and fixed before these runs.

## Tuning (scale target, working size, ablations)

${table(load('tune'))}

Target line height 34 px with a 2000 px cap gave the best fact F1 (T3). Removing normalisation costs about 7 F1 points; removing the crop costs little F1 but adds about 1 s of OCR time (Tesseract chews on the desk).

## Language

${table(final.filter((v) => v.name.includes('only') || v.name.includes('by-page') || v.name === 'default fra+eng'))}

Single-language OCR is about twice as fast under load but loses 3 to 6 F1 points even when the page language is known (oracle), because French
pages carry English words (FCFA, MoMo, "Mobile Money") and the reverse. **Decision: keep fra+eng.** A cheaper speed-up is the size cap, not the language.

## Timing (one worker at a time, desktop, 4 cores)

${table(timing)}

Phone CPUs are typically 3 to 6 times slower for WASM Tesseract, so expect roughly 10 to 20 s on a cheap phone; pre-processing (about 0.25 s here) is not the bottleneck.
Pages that read confidently take one pass (~2 s); the 180-degree retry doubles the time only for pages that came back with low confidence.

## Chosen defaults

\`PREP_DEFAULT\`: invert (dark-mode screenshots) on, crop on, illumination normalisation on, sideways detection on, deskew (+-15 deg) on, rescale to 34 px
text lines (max 3x up, 2000 px longest side) on, Sauvola off. Language fra+eng. Half-turn retry below 55 % confidence.

## Known limits

- Perspective is not corrected (only rotation); strong tilt still lowers accuracy on the harshest pages.
- 180-degree orientation: ink statistics proved unreliable (tested centroid/ascender bias: false flips on upright pages), and Tesseract OSD data (\`osd.traineddata\`) is not shipped offline, so a low-confidence half-turn retry is used instead.
- The existing sharpness check (Laplacian variance) is inflated by sensor noise: every benchmark photo, including noisy ones, passes it. Not changed here.
- The synthetic set is only a proxy; results on real photos will differ. Images are regenerated with \`OCR_BENCH_GEN=1\` (see \`gen.test.ts\`); the benchmark runs with \`OCR_BENCH=<set>\` (see \`variants.ts\`).
`;
writeFileSync('RESULTS.md', md);
