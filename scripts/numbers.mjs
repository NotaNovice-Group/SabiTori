#!/usr/bin/env node
/**
 * docs/numbers.md: every number SabiTori quotes (application, README, talks), each with its conditions and source,
 * generated from the result files so it is never out of date. `pnpm reproduce` regenerates and checks it.
 *
 *   node scripts/numbers.mjs           # write docs/numbers.md
 *   node scripts/numbers.mjs --check   # exit 1 if docs/numbers.md is not what the result files say
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const json = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const r = json('packages/understand/eval/results.json');
const ocr = json('apps/app/test/ocr-bench/results/rules.json');
const pct = (x) => `${(x * 100).toFixed(1)}%`;
const ci = (a) => `${pct(a.acc)} [${(a.lo * 100).toFixed(1)}–${(a.hi * 100).toFixed(1)}]`;

const set = (name) => r.sets[name];
const comb = (name, f) => ci(set(name).accuracy.combined[f]);
const rules = (name, f) => ci(set(name).accuracy.rules[f]);
const vs = (name) => {
  const v = set(name).vsRules.combined.all;
  return `+${(v.diff * 100).toFixed(1)} points, ${v.p < 0.001 ? 'p < 0.001' : `p = ${v.p.toFixed(3)}`}`;
};
const scam = (name) => {
  const s = set(name).scam;
  return `${s.warned} of ${s.flagged} scams warned; ${s.falseAlarms} of ${s.genuine} genuine messages falsely warned`;
};
const u2 = Boolean(r.sets.unseen2);
const u3 = Boolean(r.sets.unseen3);
const cards = json('apps/app/test/ocr-bench/results/cards.json');
const shipped = ocr.find((v) => v.name.startsWith('shipped')) ?? ocr[ocr.length - 1];

const md = `# Numbers to quote

Generated by \`scripts/numbers.mjs\` from the result files; do not edit by hand. \`pnpm reproduce\` re-runs every
evaluation and checks this page. All messages and photos are **synthetic** (written or rendered for testing); no real
message has been evaluated yet, and nothing here was measured on a phone.

## Understanding a message (kind, action, urgency)

Built-in model ${r.classifier} plus rules (heads trained on ${r.train.n} messages), thresholds chosen on the train split only.

| Set | All three right | Kind | Action | Urgency | Rules alone, all three | Model + rules vs rules |
| --- | --- | --- | --- | --- | --- | --- |
${u3 ? `| Third unseen set (${set('unseen3').n} messages by an independent author, labels checked by a second reviewer, never read while training the fine-tuned model, evaluated once): **the number to quote** | **${comb('unseen3', 'all')}** | ${comb('unseen3', 'kind')} | ${comb('unseen3', 'action')} | ${comb('unseen3', 'urgency')} | ${rules('unseen3', 'all')} | ${vs('unseen3')} |
` : ''}${u2 ? `| Second unseen set (${set('unseen2').n} messages by an independent author${u3 ? '; its overall score was seen before the fine-tune)' : ', written after the retrain and evaluated once): **the number to quote**'} | ${u3 ? '' : '**'}${comb('unseen2', 'all')}${u3 ? '' : '**'} | ${comb('unseen2', 'kind')} | ${comb('unseen2', 'action')} | ${comb('unseen2', 'urgency')} | ${rules('unseen2', 'all')} | ${vs('unseen2')} |
| First unseen set (${set('unseen').n} messages; its per-class error counts were read once to decide what training messages to add, so it is no longer untouched) | ${comb('unseen', 'all')} | ${comb('unseen', 'kind')} | ${comb('unseen', 'action')} | ${comb('unseen', 'urgency')} | ${rules('unseen', 'all')} | ${vs('unseen')} |` : `| Unseen (${set('unseen').n} messages, never used for any choice): **the number to quote** | **${comb('unseen', 'all')}** | ${comb('unseen', 'kind')} | ${comb('unseen', 'action')} | ${comb('unseen', 'urgency')} | ${rules('unseen', 'all')} | ${vs('unseen')} |`}
| Test split (${set('test').n} messages, same templates as training) | ${comb('test', 'all')} | ${comb('test', 'kind')} | ${comb('test', 'action')} | ${comb('test', 'urgency')} | ${rules('test', 'all')} | ${vs('test')} |

Brackets: 95% bootstrap intervals. Comparison: exact McNemar test on the same messages.

## Scam warnings (code, not the model)

${u3 ? `- Third unseen set: ${scam('unseen3')}.\n` : ''}${u2 ? `- Second unseen set: ${scam('unseen2')}.\n` : ''}- ${u2 ? 'First unseen' : 'Unseen'} set: ${scam('unseen')}.
- Test split: ${scam('test')} (small; the unseen set is the fairer number).

## Reading photos (on-device OCR)

${shipped.images.length} degraded synthetic photos of bills, letters and SMS screenshots: ${pct(shipped.recall)} of dates, amounts and
phone numbers recovered, ${pct(shipped.precision)} of those read are right, every fact right on ${shipped.perfect} of ${shipped.images.length} pages
(\`apps/app/test/ocr-bench/RESULTS.md\`). On the card a person sees, from the same photos: the right amount on ${cards.ocr.amount.right} of ${cards.photos} (${cards.ocr.amount.wrong} wrong, ${cards.ocr.amount.missing}
shown without an amount), the right date on ${cards.ocr.date.right} of ${cards.dated} dated pages (${cards.ocr.date.wrong} wrong, ${cards.ocr.date.missing} without a date), and no genuine
photo warned as a likely scam (${cards.ocr.falseScam}); from the photos' true text: ${cards.truth.amount.right} of ${cards.photos} amounts, ${cards.truth.date.right} of ${cards.dated} dates
(\`packages/understand/eval/run-photo-cards.mjs\`).

## Other measured facts (with their source)

- Model size: ${(r.export.onnxBytes / 1048576).toFixed(1)} MB (int8, ${(r.export.exportedParams / 1e6).toFixed(0)} M parameters).
- Slow-phone stand-in (desktop CPU slowed 4x, not a phone): a pasted bill becomes a card in 1.3 to 2.3 s depending
  on the test machine (\`docs/model.md\`, "App start and card time", 2026-11-17 and 2026-11-18). Not measured on a phone.
- Accessibility: 163 screen states, WCAG 2.2 AA (axe-core) plus manual-class checks, 0 violations
  (\`apps/app/a11y-report.md\`); no disabled person has tested the app yet (\`docs/accessibility.md\`).
`;

// The landing page (site/index.html) quotes the same numbers: its two rows between the markers are generated here
// too, so the page can never drift from the result files.
const main = u2 ? 'unseen2' : 'unseen';
const mainName = u2 ? 'Second unseen set: 100 synthetic messages by an independent author, evaluated once' : 'Unseen set: 100 synthetic messages, never used for any choice';
const v = set(main).vsRules.combined.all;
const pTxt = v.p < 0.001 ? 'p < 0.001' : `p = ${v.p.toFixed(3)}`;
const sig = v.p < 0.05 ? 'a significant difference' : 'not a significant difference';
const first = u2 ? set('unseen') : undefined;
const s2 = set(main).scam;
const siteRows = [
  '<!-- numbers:start (generated by scripts/numbers.mjs; do not edit by hand) -->',
  `            <tr><th scope="row">Scam warnings</th><td><strong>${s2.warned} of ${s2.flagged}</strong> scams warned; <strong>${s2.falseAlarms} of ${s2.genuine}</strong> genuine messages falsely warned</td><td>${mainName}.${first ? ` First unseen set: ${first.scam.warned} of ${first.scam.flagged} warned, ${first.scam.falseAlarms} of ${first.scam.genuine} false alarms` : ''}</td></tr>`,
  `            <tr><th scope="row">Understanding a message (kind, action and urgency all right)</th><td><strong>${pct(set(main).accuracy.combined.all.acc)}</strong> [${(set(main).accuracy.combined.all.lo * 100).toFixed(1)}–${(set(main).accuracy.combined.all.hi * 100).toFixed(1)}], against ${rules(main, 'all')} for rules alone</td><td>${u2 ? 'Second unseen set' : 'Unseen set'}; +${(v.diff * 100).toFixed(1)} points, ${pTxt}, ${sig} (exact McNemar test).${first ? ` First unseen set: ${pct(first.accuracy.combined.all.acc)} against ${pct(first.accuracy.rules.all.acc)}, ${vs('unseen')}.` : ''} Brackets are 95% bootstrap intervals</td></tr>`,
  '            <!-- numbers:end -->',
].join('\n');
const sitePath = join(root, 'site/index.html');
let site = '';
try {
  site = readFileSync(sitePath, 'utf8');
} catch {
  /* no landing page */
}
const markers = /<!-- numbers:start[\s\S]*?<!-- numbers:end -->/;
const siteOut = site && markers.test(site) ? site.replace(markers, siteRows) : site;

const out = join(root, 'docs/numbers.md');
if (process.argv.includes('--check')) {
  let cur = '';
  try {
    cur = readFileSync(out, 'utf8');
  } catch {
    /* missing */
  }
  if (cur !== md) {
    console.error('docs/numbers.md is out of date: run node scripts/numbers.mjs');
    process.exit(1);
  }
  if (siteOut !== site) {
    console.error('site/index.html numbers are out of date: run node scripts/numbers.mjs');
    process.exit(1);
  }
  console.log('docs/numbers.md and the landing page numbers are up to date.');
} else {
  writeFileSync(out, md);
  if (siteOut !== site) writeFileSync(sitePath, siteOut);
  console.log('wrote docs/numbers.md and the landing page numbers');
}
